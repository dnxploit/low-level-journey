/* Chapter 2, Exercise 4: int and float declarations without initialization */

#include <stdio.h>

int main(void)
{
    int x, y, z;
    float a, b, c;

    printf("%d\n", x);
    printf("%d\n", y);
    printf("%d\n", z);

    printf("%f\n", a);
    printf("%f\n", b);
    printf("%f\n", c);

    return 0;
}